"""Generate the synthetic CC0 `ci` eval dataset (deterministic; re-running is byte-identical)."""

import json
import re
from pathlib import Path

import numpy as np
import soundfile as sf
from music21 import clef, instrument, key, meter, note, pitch, stream, tempo
from transcritor_eval.dataset import RefNote, write_reference_notes

OUT = Path(__file__).resolve().parents[1] / "datasets" / "ci"
ITEM_ID = "c_major_scale_flute"
PITCHES = [60, 62, 64, 65, 67, 69, 71, 72]
NOTE_S = 0.5
SAMPLE_RATE = 22050
AMPLITUDE = 0.3
FADE_S = 0.010
TAIL_S = 0.5
DOWNBEATS = [0.0, 2.0, 4.0]


def make_audio() -> np.ndarray:
    total = round((len(PITCHES) * NOTE_S + TAIL_S) * SAMPLE_RATE)
    audio = np.zeros(total, dtype=np.float64)
    n = round(NOTE_S * SAMPLE_RATE)
    fade = round(FADE_S * SAMPLE_RATE)
    envelope = np.ones(n)
    envelope[:fade] = np.linspace(0.0, 1.0, fade)
    envelope[-fade:] = np.linspace(1.0, 0.0, fade)
    t = np.arange(n) / SAMPLE_RATE
    for i, midi in enumerate(PITCHES):
        freq = 440.0 * 2.0 ** ((midi - 69) / 12)
        audio[i * n : (i + 1) * n] = AMPLITUDE * envelope * np.sin(2 * np.pi * freq * t)
    return audio


def make_score() -> stream.Score:
    part = stream.Part()
    part.partName = "Flute"
    flute = instrument.Flute()
    flute.instrumentId = "I1"  # music21 would otherwise emit a random id
    part.insert(0, flute)
    part.append(clef.TrebleClef())
    part.append(key.KeySignature(0))
    part.append(meter.TimeSignature("4/4"))
    part.append(tempo.MetronomeMark(number=120))
    for midi in PITCHES:
        # Spell from the name: a Note built from a MIDI int makes music21 emit spurious
        # <accidental>natural</accidental> tags after the first measure.
        name = pitch.Pitch(midi=midi).nameWithOctave
        part.append(note.Note(name, quarterLength=1.0))
    part.makeMeasures(inPlace=True)
    score = stream.Score()
    score.insert(0, part)
    return score


def main() -> None:
    (OUT / "audio").mkdir(parents=True, exist_ok=True)
    (OUT / "refs").mkdir(parents=True, exist_ok=True)

    sf.write(OUT / "audio" / f"{ITEM_ID}.wav", make_audio(), SAMPLE_RATE, subtype="PCM_16")

    xml_path = OUT / "refs" / f"{ITEM_ID}.musicxml"
    make_score().write("musicxml", fp=str(xml_path))
    # music21 stamps the current date and a random part id; normalize both so re-runs match.
    xml = re.sub(r"\s*<encoding-date>[^<]*</encoding-date>", "", xml_path.read_text("utf-8"))
    xml = re.sub(r'"P[0-9a-f]{32}"', '"P1"', xml)
    xml_path.write_text(xml, encoding="utf-8")

    notes = [RefNote(i * NOTE_S, (i + 1) * NOTE_S, p) for i, p in enumerate(PITCHES)]
    write_reference_notes(notes, OUT / "refs" / f"{ITEM_ID}.notes.csv")

    downbeats = "".join(f"{d:.1f}\n" for d in DOWNBEATS)
    (OUT / "refs" / f"{ITEM_ID}.downbeats.txt").write_text(downbeats, encoding="utf-8")

    manifest = {
        "name": "ci",
        "audio_root": "manifest",
        "items": [
            {
                "id": ITEM_ID,
                "instrument": "flute",
                "audio": f"audio/{ITEM_ID}.wav",
                "audio_sha256": None,
                "reference_notes": f"refs/{ITEM_ID}.notes.csv",
                "reference_score": f"refs/{ITEM_ID}.musicxml",
                "reference_downbeats": f"refs/{ITEM_ID}.downbeats.txt",
                "key": {"tonic_step": "C", "tonic_alter": 0, "mode": "major"},
                "license": "CC0-1.0",
                "source": "synthetic, generated by make_ci_fixture.py",
                "subsets": ["ci"],
            }
        ],
    }
    (OUT / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
